"""プロジェクト側の準備（`scripts/sdlc init`）: ランチャ・AGENTS.md の参照・.gitignore。

本体は ~/.codex/sdlc（全プロジェクト共通）またはプロジェクトの .codex/sdlc に置く。
プロジェクトには本体へのランチャ scripts/sdlc・scripts/approve だけを置き、どちらの配置でも同じコマンドで使えるようにする。
"""
from __future__ import annotations

import os
import re
from pathlib import Path

LAUNCHER = r'''#!/usr/bin/env bash
# SDLC ワークフローのランチャ（scripts/sdlc init が生成。編集しない）。
# 本体はプロジェクトの .codex/sdlc/bin を優先し、無ければ ~/.codex/sdlc/bin を使う。
# Windows の PowerShell / コマンドプロンプトでは同じ名前の .cmd を使う。
src="${BASH_SOURCE[0]//\\//}"          # Windows のパス（C:\...）でも動くよう区切りを / にそろえる
root="$(cd "${src%/*}/.." && pwd)"
name="${src##*/}"
user_home="${HOME:-$USERPROFILE}"
if [ -n "${WINDIR:-}" ] && [ -n "${USERPROFILE:-}" ]; then user_home="$USERPROFILE"; fi
user_base="${CODEX_HOME:-$user_home/.codex}"
for base in "$root/.codex" "${user_base//\\//}"; do
  [ -n "$base" ] || continue
  if [ -f "$base/sdlc/bin/$name" ]; then
    exec bash "$base/sdlc/bin/py" "$base/sdlc/bin/$name" "$@"
  fi
done
echo "SDLC ワークフロー本体（.codex/sdlc/bin/${name}）が見つかりません。USAGE.md のインストール手順を参照してください。" >&2
exit 1
'''

# cmd.exe はバッチファイルをコンソールのコードページ（日本語環境では cp932）で読むため、ASCII だけで書く
LAUNCHER_CMD = r'''@echo off
rem SDLC workflow launcher (generated by "scripts/sdlc init"; do not edit). For PowerShell / Command Prompt.
rem Uses the project's .codex\sdlc\bin first, then %USERPROFILE%\.codex\sdlc\bin.
setlocal
set "PYTHONUTF8=1"
set "NAME=%~n0"
set "BIN=%~dp0..\.codex\sdlc\bin\%NAME%"
if exist "%BIN%" goto found
if defined CODEX_HOME (
  set "BIN=%CODEX_HOME%\sdlc\bin\%NAME%"
) else (
  set "BIN=%USERPROFILE%\.codex\sdlc\bin\%NAME%"
)
:found
if not exist "%BIN%" goto notfound
if defined SDLC_PYTHON goto custom
where py >nul 2>nul
if errorlevel 1 goto plain
py -3 "%BIN%" %*
exit /b
:plain
python "%BIN%" %*
exit /b
:custom
%SDLC_PYTHON% "%BIN%" %*
exit /b
:notfound
echo SDLC workflow body (.codex\sdlc\bin\%NAME%) was not found. See USAGE.md for installation. 1>&2
exit /b 1
'''

RULES_MARK = "<!-- sdlc-workflow-light-codex: rules -->"
RULES_END = "<!-- /sdlc-workflow-light-codex: rules -->"
RULES_BLOCK = re.compile(re.escape(RULES_MARK) + r".*?" + re.escape(RULES_END), re.DOTALL)
GITIGNORE_LINES = [".sdlc/"]
# Windows の git（core.autocrlf）で bash スクリプトの改行が CRLF にならないようにする
GITATTRIBUTES_LINES = ["scripts/sdlc text eol=lf", "scripts/approve text eol=lf",
                       "scripts/*.cmd text eol=crlf", ".codex/sdlc/bin/* text eol=lf",
                       ".codex/hooks/sdlc/run text eol=lf"]


def write_launchers(root) -> list[str]:
    out = []
    for name in ("sdlc", "approve"):
        for fname, text, newline in ((name, LAUNCHER, "\n"), (f"{name}.cmd", LAUNCHER_CMD, "\r\n")):
            p = Path(root) / "scripts" / fname
            data = text.replace("\n", newline).encode("utf-8")
            if p.exists() and p.read_bytes() == data:
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
            os.chmod(p, 0o755)
            out.append(p.relative_to(root).as_posix())
    return out


def ensure_agents_md(root) -> bool:
    """既存のプロジェクト指示を保ち、SDLC を使う時だけ読むルールの参照を追加する。"""
    p = Path(root) / "AGENTS.md"
    block = (
        f"{RULES_MARK}\n"
        "## SDLC ワークフロー（軽量版）\n\n"
        "SDLC 作業に入る前に `scripts/sdlc path RULES.md` を実行し、返されたファイルを読む。\n"
        "承認と受入結果の記入はユーザーが行う。\n"
        f"{RULES_END}"
    )
    text = p.read_text(encoding="utf-8") if p.exists() else ""
    if RULES_BLOCK.search(text):
        new = RULES_BLOCK.sub(lambda _: block, text, count=1)
    else:
        new = text.rstrip("\n") + ("\n\n" if text.strip() else "") + block + "\n"
    if new == text:
        return False
    p.write_text(new, encoding="utf-8")
    return True


def _ensure_lines(path: Path, lines: list[str]) -> list[str]:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    have = {ln.strip() for ln in text.splitlines()}
    add = [ln for ln in lines if ln not in have]
    if add:
        path.write_text(text.rstrip("\n") + ("\n" if text.strip() else "") + "\n".join(add) + "\n", encoding="utf-8")
    return add


def ensure_gitignore(root) -> list[str]:
    return _ensure_lines(Path(root) / ".gitignore", GITIGNORE_LINES)


def ensure_gitattributes(root) -> list[str]:
    return _ensure_lines(Path(root) / ".gitattributes", GITATTRIBUTES_LINES)
